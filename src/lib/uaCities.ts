export const normalizeCityKey = (raw: string) =>
  raw
    .toLowerCase()
    .replace(/^(м\.|місто|с\.|село|смт\.?|селище)\s*/i, "")
    .replace(/[’`]/g, "'")
    .trim();

export const findCityCoords = (raw: string): [number, number] | null => {
  const key = normalizeCityKey(raw);
  if (!key) return null;
  if (UA_CITY_COORDS[key]) return UA_CITY_COORDS[key];
  // try matching any known city contained in the string
  for (const name of Object.keys(UA_CITY_COORDS)) {
    if (name.length > 3 && key.includes(name)) return UA_CITY_COORDS[name];
  }
  return null;
};

export const prettyCity = (raw: string) =>
  normalizeCityKey(raw)
    .split(/([ -])/)
    .map((part) => (part === " " || part === "-" ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join("");
